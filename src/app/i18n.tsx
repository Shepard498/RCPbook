const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    const savedLanguage = localStorage.getItem("recipe-app-language");
    return savedLanguage === "es" ? "es" : "en";
  });

  const value = useMemo<I18nContextValue>(
    () => ({
      language,
      setLanguage: (nextLanguage) => {
        localStorage.setItem("recipe-app-language", nextLanguage);
        setLanguageState(nextLanguage);
      },
      t: (key, values) => interpolate(language === "es" ? translations[key] ?? key : key, values),
    }),
    [language],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);

  if (!context) {
    throw new Error("useI18n must be used inside I18nProvider");
  }

  return context;
}

export function translateWarning(t: I18nContextValue["t"], warning: string): string {
  if (warning.includes(": ")) {
    const [prefix, ...rest] = warning.split(": ");
    return `${prefix}: ${translateWarning(t, rest.join(": "))}`;
  }

  return t(warning);
}

function interpolate(text: string, values?: Record<string, string | number>) {
  if (!values) {
    return text;
  }

  return Object.entries(values).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    text,
  );
}
